create policy "Users can read their profile" on public.profiles for select to authenticated using (auth.uid() = id);
create policy "Users can update their profile" on public.profiles for update to authenticated using (auth.uid() = id);
create policy "Public can read subjects" on public.subjects for select to authenticated using (true);
create policy "Public can read correlatives" on public.correlatives for select to authenticated using (true);
create policy "Users manage their subject history" on public.user_subjects for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Authenticated users read published posts" on public.community_posts for select to authenticated using (is_published = true);

create or replace function public.handle_new_profile()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'nombre', 'Estudiante'));
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
  after insert on auth.users
  for each row execute procedure public.handle_new_profile();

