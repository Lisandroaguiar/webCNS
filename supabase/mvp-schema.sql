-- Esquema MVP de Cronopios / Diseño Multimedial.
-- Ejecutar en Supabase SQL Editor. Todas las tablas usan UUID del usuario autenticado.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  degree text not null default 'Diseño Multimedial',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.subjects (
  id bigint generated by default as identity primary key,
  name text not null,
  code text unique,
  year smallint not null check (year between 1 and 5),
  semester smallint check (semester between 1 and 2),
  created_at timestamptz not null default now()
);
alter table public.subjects add column if not exists curriculum text not null default 'old';
alter table public.profiles add column if not exists curriculum text not null default 'old';

create table if not exists public.correlatives (
  subject_id bigint not null references public.subjects(id) on delete cascade,
  required_subject_id bigint not null references public.subjects(id) on delete cascade,
  primary key (subject_id, required_subject_id),
  check (subject_id <> required_subject_id)
);

-- Compatibilidad con tablas existentes. El tipo de las claves debe coincidir
-- exactamente con subjects.id (algunas instalaciones previas usaban uuid).
do $$
declare
  subject_id_type text;
  correlatives_subject_type text;
  correlatives_required_type text;
begin
  select format_type(a.atttypid, a.atttypmod)
    into subject_id_type
    from pg_attribute a
    where a.attrelid = 'public.subjects'::regclass
      and a.attname = 'id'
      and not a.attisdropped;

  if subject_id_type = 'uuid' then
    select format_type(a.atttypid, a.atttypmod)
      into correlatives_subject_type
      from pg_attribute a
      where a.attrelid = 'public.correlatives'::regclass
        and a.attname = 'subject_id'
        and not a.attisdropped;
    select format_type(a.atttypid, a.atttypmod)
      into correlatives_required_type
      from pg_attribute a
      where a.attrelid = 'public.correlatives'::regclass
        and a.attname = 'required_subject_id'
        and not a.attisdropped;

    if correlatives_subject_type is null or correlatives_required_type is null then
      alter table public.correlatives add column if not exists subject_id uuid;
      alter table public.correlatives add column if not exists required_subject_id uuid;
    elsif correlatives_subject_type <> 'uuid' or correlatives_required_type <> 'uuid' then
      raise exception 'public.correlatives usa tipos incompatibles (% y %), mientras subjects.id usa uuid. Respaldá y migrá esas filas antes de continuar.',
        correlatives_subject_type, correlatives_required_type;
    end if;

    if not exists (
      select 1 from pg_constraint
      where conname = 'correlatives_subject_id_fkey'
        and conrelid = 'public.correlatives'::regclass
    ) then
      alter table public.correlatives
        add constraint correlatives_subject_id_fkey
        foreign key (subject_id) references public.subjects(id) on delete cascade;
    end if;
    if not exists (
      select 1 from pg_constraint
      where conname = 'correlatives_required_subject_id_fkey'
        and conrelid = 'public.correlatives'::regclass
    ) then
      alter table public.correlatives
        add constraint correlatives_required_subject_id_fkey
        foreign key (required_subject_id) references public.subjects(id) on delete cascade;
    end if;
  elsif subject_id_type in ('bigint', 'integer') then
    alter table public.correlatives add column if not exists subject_id bigint;
    alter table public.correlatives add column if not exists required_subject_id bigint;
    if not exists (
      select 1 from pg_constraint
      where conname = 'correlatives_subject_id_fkey'
        and conrelid = 'public.correlatives'::regclass
    ) then
      alter table public.correlatives
        add constraint correlatives_subject_id_fkey
        foreign key (subject_id) references public.subjects(id) on delete cascade;
    end if;
    if not exists (
      select 1 from pg_constraint
      where conname = 'correlatives_required_subject_id_fkey'
        and conrelid = 'public.correlatives'::regclass
    ) then
      alter table public.correlatives
        add constraint correlatives_required_subject_id_fkey
        foreign key (required_subject_id) references public.subjects(id) on delete cascade;
    end if;
  end if;
end $$;

create table if not exists public.user_subjects (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  subject_id bigint not null references public.subjects(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending', 'regular', 'passed')),
  grade numeric(3,1) check (grade between 1 and 10),
  passed_at date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, subject_id)
);

-- Compatibilidad con user_subjects de una instalación anterior.
-- La aplicación actual utiliza estos nombres para guardar estado, nota y fecha.
alter table public.user_subjects add column if not exists status text default 'pending';
alter table public.user_subjects add column if not exists grade numeric(3,1);
alter table public.user_subjects add column if not exists passed_at date;
alter table public.user_subjects add column if not exists created_at timestamptz not null default now();
alter table public.user_subjects add column if not exists updated_at timestamptz not null default now();

-- Normaliza el CHECK de status de instalaciones anteriores. La app utiliza
-- exclusivamente pending, regular y passed.
do $$
declare
  constraint_record record;
begin
  update public.user_subjects
  set status = case lower(status::text)
    when 'pendiente' then 'pending'
    when 'aprobada' then 'passed'
    when 'aprobado' then 'passed'
    when 'regularizada' then 'regular'
    when 'in_progress' then 'regular'
    when 'completed' then 'passed'
    else status
  end
  where status is not null;

  for constraint_record in
    select conname
    from pg_constraint
    where conrelid = 'public.user_subjects'::regclass
      and contype = 'c'
      and pg_get_constraintdef(oid) ilike '%status%'
  loop
    execute format('alter table public.user_subjects drop constraint if exists %I', constraint_record.conname);
  end loop;

  alter table public.user_subjects
    add constraint user_subjects_status_check
    check (status in ('pending', 'regular', 'passed'));
end $$;

create table if not exists public.community_posts (
  id bigint generated by default as identity primary key,
  author_id uuid references auth.users(id) on delete set null,
  title text not null,
  body text not null,
  event_type text not null default 'aviso',
  event_date date,
  accent text not null default 'lime' check (accent in ('lime', 'fuchsia', 'cyan')),
  is_published boolean not null default true,
  created_at timestamptz not null default now()
);

-- Compatibilidad con una tabla community_posts creada por una versión anterior.
-- CREATE TABLE IF NOT EXISTS no modifica columnas de tablas existentes.
alter table public.community_posts add column if not exists author_id uuid references auth.users(id) on delete set null;
alter table public.community_posts add column if not exists title text;
alter table public.community_posts add column if not exists body text;
alter table public.community_posts add column if not exists event_type text default 'aviso';
alter table public.community_posts add column if not exists event_date date;
alter table public.community_posts add column if not exists accent text default 'lime';
alter table public.community_posts add column if not exists is_published boolean not null default true;
alter table public.community_posts add column if not exists created_at timestamptz not null default now();

